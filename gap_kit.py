"""空窗期处理套件 —— 简历怎么写 + 面试怎么答。

为什么这件事单独做
------------------
2025 届毕业到 2026-10，简历上有一段一年多的时间空白，面试 100% 会问
「这段时间你在做什么」。这不是加分项，是**扣分项**：答不好直接挂，
答得好也只是不扣分。所以必须提前准备到能背出来的程度。

三条原则（比话术本身更重要）
--------------------------
1. **不解释，给证据**：不要说「我在家学习」，要说「我做了 X，这是链接」。
2. **不道歉**：空窗是事实，不是过错。用陈述句，不用「不好意思/比较惭愧」。
3. **往前看**：回答完加一句「所以我现在想做的是……」，把话题拉回岗位。

三种长度的回答（面试官会按你的第一句决定要不要深入）
----------------------------------------------------
- one_liner：一句话，用于「简单说一下」
- expanded：三句话，用于「详细讲讲」
- followup：被追问「为什么不去上班/是不是找不到」时的应答
"""
