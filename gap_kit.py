# ── 通用原则 ───────────────────────────────────────────────────
PRINCIPLES = [
    "回答控制在 30 秒内，说完停下来——话越多破绽越多",
    "先给结论（我在做项目），再给证据（GitHub/项目名），不要从「那时候我……」开始讲",
    "绝不说「找不到工作」——这句一出，面试基本结束",
    "绝不说「在家躺了一段时间」——哪怕是玩笑",
    "被追问细节时，讲项目里的技术决策，不讲心路历程",
    "结尾一定加一句「所以我现在的目标很明确，就是……」把球踢回去",
]


def get(scenario: str) -> dict:
    """取一个场景；不存在时抛 KeyError 而不是静默返回空——配置错了要暴露。"""
    if scenario not in SCENARIOS:
        raise KeyError(f"未知场景 {scenario!r}，可选：{', '.join(SCENARIOS)}")
    return {"name": scenario, **SCENARIOS[scenario]}


def all_scenarios() -> list[str]:
    return list(SCENARIOS)


def check_answer(text: str) -> list[str]:
    """检查一段自述里有没有踩雷的表述。返回命中的问题列表（空 = 没明显问题）。"""
    t = str(text or "")
    hits = []
    red = {
        "找不到工作": "这句话一出，面试基本结束",
        "没找到工作": "同上，换成「在探索方向/做项目」",
        "躺": "哪怕开玩笑也不行",
        "惭愧": "空窗不是过错，不要道歉",
        "不好意思": "不要道歉，用陈述句",
        "一直在学习": "面试官只认产出，不认学习",
        "迷茫": "显示方向不明确",
        "试试看": "显示没有决心",
    }
    for k, why in red.items():
        if k in t:
            hits.append(f"「{k}」—— {why}")
    if len(t) < 20:
        hits.append("太短了，至少给一句完整的结论 + 一个证据")
    return hits


